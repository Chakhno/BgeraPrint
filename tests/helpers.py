#!/usr/bin/env python
# coding: utf-8
"""
Bits the tests share.

The main job here is finding OpenSCAD.  On a developer's machine it may be
installed normally and sit on the PATH.  On a classroom machine it will not
be installed at all -- it lives in assets/bin next to the app.  The tests
look in both places, so they work either way and nobody has to install
anything to run them.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent.parent
BIN = APP_DIR / "assets" / "bin"


def find_openscad():
    """The OpenSCAD to test with: the bundled one first, then the PATH."""
    for candidate in (BIN / "openscad.exe", BIN / "openscad"):
        if candidate.exists():
            return candidate
    found = shutil.which("openscad") or shutil.which("openscad.exe")
    return Path(found) if found else None


def find_slicer():
    """The real PrusaSlicer, if it is here.  None if it is not."""
    for candidate in (BIN / "prusa-slicer-console.exe",
                      BIN / "prusa-slicer-console",
                      BIN / "prusa-slicer"):
        if candidate.exists():
            return candidate
    found = shutil.which("prusa-slicer-console") or shutil.which("prusa-slicer")
    return Path(found) if found else None


def with_bin_on_path():
    """
    PrusaSlicer and OpenSCAD load their DLLs from the folder they sit in.
    Without this they start and die with no message, which is exactly the
    failure the app itself guards against, so the tests must guard too.
    """
    if BIN.exists() and str(BIN) not in os.environ.get("PATH", ""):
        os.environ["PATH"] = os.environ.get("PATH", "") + os.pathsep + str(BIN)


OPENSCAD = find_openscad()
SLICER = find_slicer()
with_bin_on_path()


