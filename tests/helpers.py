STUB_SLICER = r'''#!/usr/bin/env python3
"""A stand-in for PrusaSlicer, so sessions can be tested with no printer."""
import sys

args = sys.argv[1:]

if "--info" in args:
    print("size_x = 40")
    print("size_y = 20")
    print("size_z = 10")
    sys.exit(0)

out = args[args.index("--output") + 1] if "--output" in args else "out.gcode"
with open(out, "w") as handle:
    handle.write(
        "; generated by a stand-in slicer\n"
        "; estimated printing time (normal mode) = 1h 12m 30s\n"
        "; filament used [g] = 14.62\n"
        "; filament used [mm] = 4900.3\n"
        "; total layers count = 100\n")
sys.exit(0)
'''


def make_stub_slicer(folder):
    """
    Write the stand-in and give back a command that runs it.

    A command, not a path: on Windows a .py file cannot be started as a
    program, so it has to be handed to Python.  printing.as_command accepts
    either form, which is what makes this work on both.
    """
    script = Path(folder) / "stub_slicer.py"
    script.write_text(STUB_SLICER, encoding="utf-8")
    if os.name != "nt":
        script.chmod(script.stat().st_mode | 0o111)
    return [sys.executable, str(script)]


