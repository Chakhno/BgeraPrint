def compile_scad(scad_text, timeout=180):
    """Run OpenSCAD on some code.  Returns (ok, message, size_of_stl)."""
    with tempfile.TemporaryDirectory() as folder:
        scad = Path(folder) / "m.scad"
        stl = Path(folder) / "m.stl"
        scad.write_text(scad_text, encoding="utf-8")
        try:
            result = subprocess.run([str(OPENSCAD), "-o", str(stl), str(scad)],
                                    capture_output=True, text=True,
                                    timeout=timeout)
        except subprocess.TimeoutExpired:
            return False, "OpenSCAD took too long.", 0
        size = stl.stat().st_size if stl.exists() else 0
        return result.returncode == 0 and size > 0, result.stderr, size
